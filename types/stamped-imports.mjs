// Writes types/stamped-imports.d.ts, which lets the TypeScript checker follow the
// cache-busting stamps that bump_assets.py puts on every relative import, for example
// import { latin1 } from './bytes.js?v=4d7df4d3'.
//
// The browser treats the ?v= part as part of the address; the checker cannot, and has no
// setting that strips it. So for each stamped specifier this file declares a module whose
// name is that specifier (as a pattern, because a declared module name may not start with
// ./) and which re-exports the real file through the "ms-src/*" path in jsconfig.json.
// The checker then sees the real module, with its real types, behind every stamped import.
//
// The stamps change whenever bump_assets.py runs, so `npm run typecheck` runs this first.
// Usage: node types/stamped-imports.mjs [--check]   (--check exits 1 if the file is stale)
// Type checking only: nothing here is served, and the app never loads it.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'types', 'stamped-imports.d.ts');
const IMPORT_RE = /\b(?:import|export)\b[^'"`;]*?\bfrom\s*(['"])(\.{1,2}\/[^'"?#]+\.js)\?v=([0-9a-f]+)\1/g;

/** @param {string} dir @returns {string[]} */
function jsFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? jsFiles(join(dir, d.name)) : d.name.endsWith('.js') ? [join(dir, d.name)] : []);
}

const lines = new Map();
for (const file of [join(ROOT, 'app.js'), ...jsFiles(join(ROOT, 'src'))]) {
  for (const m of readFileSync(file, 'utf8').matchAll(IMPORT_RE)) {
    const target = resolve(dirname(file), m[2]);
    const rel = relative(join(ROOT, 'src'), target).split(sep).join('/');
    if (rel.startsWith('..')) throw new Error(`${file}: ${m[2]} points outside src/`);
    const name = `*/${m[2].replace(/^(?:\.{1,2}\/)+/, '')}?v=${m[3]}`;
    lines.set(name, `declare module '${name}' { export * from 'ms-src/${rel}'; }`);
  }
}

const text = [
  '// Generated by types/stamped-imports.mjs; do not edit. Type checking only, never served.',
  ...[...lines.keys()].sort().map((k) => lines.get(k)),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('types/stamped-imports.d.ts is stale: run node types/stamped-imports.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
}
